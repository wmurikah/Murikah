/** Generate db/schema.sql from the numbered migration chain. The migration
 * files are the source of truth; this snapshot exists for review and tooling. */
import { createClient } from '@libsql/client';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { runMigrations } from './migrate.ts';

// A file-backed disposable database is used because libSQL transactions may use
// another connection; separate connections do not share `file::memory:`.
const temp = mkdtempSync(join(tmpdir(), 'engr-schema-'));
const client = createClient({ url: `file:${join(temp, 'schema.db')}` });
try {
  await runMigrations(client);
  const objects = await client.execute({
    sql: `SELECT type, name, sql FROM sqlite_schema
           WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
        ORDER BY CASE type WHEN 'table' THEN 1 WHEN 'index' THEN 2 WHEN 'view' THEN 3 ELSE 4 END,
                 name`,
    args: [],
  });
  const header = `-- ============================================================================
-- ENGINEERING RHYTHM canonical schema snapshot
-- GENERATED by db/generate-schema.ts from db/migrations. DO NOT EDIT DIRECTLY.
-- CLEAN INSTALLS ONLY. DO NOT RUN THIS SNAPSHOT AGAINST AN EXISTING DATABASE.
-- Existing databases and upgrades must run the conditional, checksum-verified
-- numbered migrations through db/apply.ts. This file is a review/tooling
-- artifact verified by tests; duplicate-object errors are expected if it is
-- pasted into an already-created database.
-- ============================================================================\n\n`;
  const body = objects.rows.map((row) => `${String(row.sql).trim()};`).join('\n\n');
  const output = `${header}${body}\n`;
  const destination = new URL('./schema.sql', import.meta.url);
  if (process.argv.includes('--check')) {
    const current = readFileSync(destination, 'utf8');
    if (current !== output) {
      throw new Error('db/schema.sql is stale. Run pnpm db:schema:generate and commit it.');
    }
    console.log(`✓ db/schema.sql matches ${objects.rows.length} migrated schema objects.`);
  } else {
    writeFileSync(destination, output);
    console.log(`✓ Generated db/schema.sql from ${objects.rows.length} schema objects.`);
  }
} finally {
  client.close();
  rmSync(temp, { recursive: true, force: true });
}
