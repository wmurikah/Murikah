/** Generate the reviewed seed and Turso Web RBAC scripts from migration 006.
 * This prevents the application migration, clean install and manual production
 * rollout from silently drifting into different role definitions. */
import { readFileSync, writeFileSync } from 'node:fs';
import {
  comprehensiveRbac,
  RBAC_PERMISSIONS,
  RETIRED_PERMISSIONS,
  STANDARD_ROLES,
  STANDARD_ROLE_GRANTS,
} from './migrations/006_comprehensive_rbac.ts';

const q = (value: string): string => `'${value.replaceAll("'", "''")}'`;
const allPermissions = RBAC_PERMISSIONS.map(([key]) => key);
const pairs = Object.entries(STANDARD_ROLE_GRANTS).flatMap(([role, grants]) =>
  (grants === 'ALL' ? allPermissions : grants).map((permission) => [role, permission] as const),
);
const values = (rows: readonly (readonly string[])[], indent = '  '): string =>
  rows.map((row) => `${indent}(${row.map(q).join(',')})`).join(',\n');

const permissionSql = `INSERT INTO permissions (key, module, description) VALUES\n${values(RBAC_PERMISSIONS)}\nON CONFLICT(key) DO UPDATE SET module = excluded.module, description = excluded.description;`;
const retiredSql = `DELETE FROM permissions WHERE key IN (${RETIRED_PERMISSIONS.map(q).join(',')});`;
const rolesSql = `INSERT OR IGNORE INTO roles (org_id, code, name, description, is_system) VALUES\n${STANDARD_ROLES.map(([code, name, description]) => `  (NULL,${q(code)},${q(name)},${q(description)},1)`).join(',\n')};\n\n${STANDARD_ROLES.map(([code, , description]) => `UPDATE roles SET description = ${q(description)} WHERE code = ${q(code)};`).join('\n')}`;

const standardCodes = STANDARD_ROLES.map(([code]) => code);
const grantSql = `DELETE FROM role_permissions WHERE role_id IN (\n  SELECT id FROM roles WHERE code IN (${standardCodes.map(q).join(',')})\n);\n\nWITH expected(role_code, permission_key) AS (\n  VALUES\n${values(pairs)}\n)\nINSERT OR IGNORE INTO role_permissions (role_id, permission_id)\nSELECT r.id, p.id FROM expected e\nJOIN roles r ON r.code = e.role_code\nJOIN permissions p ON p.key = e.permission_key;`;

const seedPath = new URL('./seed.sql', import.meta.url);
const currentSeed = readFileSync(seedPath, 'utf8');
const marker =
  '-- ---------------------------------------------------------------------------\n-- Reviewed permission registry.';
const seedPrefix = currentSeed.slice(0, currentSeed.indexOf(marker));
if (!seedPrefix) throw new Error('Could not locate the RBAC section in db/seed.sql');
writeFileSync(
  seedPath,
  `${seedPrefix}${marker}\n-- Generated by db/generate-rbac-sql.ts.\n-- ---------------------------------------------------------------------------\n${retiredSql}\n\n${permissionSql}\n\n-- Nine shared defaults. Migration 006 reconciles existing organisation copies.\n${rolesSql}\n\nDELETE FROM role_permissions WHERE role_id IN (\n  SELECT id FROM roles WHERE org_id IS NULL AND code IN (${standardCodes.map(q).join(',')})\n);\n\nINSERT OR IGNORE INTO role_permissions (role_id, permission_id)\nSELECT r.id, p.id FROM roles r CROSS JOIN permissions p\n WHERE r.org_id IS NULL AND r.code IN ('OWNER','ADMIN');\n\nWITH expected(role_code, permission_key) AS (\n  VALUES\n${values(pairs.filter(([role]) => role !== 'OWNER' && role !== 'ADMIN'))}\n)\nINSERT OR IGNORE INTO role_permissions (role_id, permission_id)\nSELECT r.id, p.id FROM expected e\nJOIN roles r ON r.org_id IS NULL AND r.code = e.role_code\nJOIN permissions p ON p.key = e.permission_key;\n\n-- End of seed.\n`,
);

const checks = `-- Run before 14_apply_comprehensive_rbac.sql and again afterwards.
-- Before applying, all nine columns and migration 006 should be missing.
-- After applying, missing/duplicate/unexpected/retired queries return zero rows.
WITH required(table_name, column_name) AS (
  VALUES ('lpos','submitted_at'),('lpos','submitted_by'),
         ('rfqs','submitted_at'),('rfqs','submitted_by'),('rfqs','released_at'),('rfqs','released_by'),
         ('pm_schedules','created_by'),('pm_schedules','activated_by'),('pm_schedules','activated_at')
)
SELECT required.table_name, required.column_name AS missing_column
FROM required
WHERE NOT EXISTS (
  SELECT 1 FROM pragma_table_info(required.table_name) columns
  WHERE columns.name = required.column_name
);

SELECT id, description, checksum, applied_at FROM schema_migrations WHERE id = '006';
SELECT id, checksum AS wrong_checksum FROM schema_migrations
 WHERE id = '006' AND checksum <> ${q(comprehensiveRbac.checksum)};

SELECT 'contractor portal user' AS duplicate_type, portal_user_id AS duplicate_key, COUNT(*) AS row_count
  FROM contractors WHERE portal_user_id IS NOT NULL GROUP BY portal_user_id HAVING COUNT(*) > 1;
SELECT 'technician portal user' AS duplicate_type, portal_user_id AS duplicate_key, COUNT(*) AS row_count
  FROM technicians WHERE portal_user_id IS NOT NULL GROUP BY portal_user_id HAVING COUNT(*) > 1;
SELECT 'station engineer routing' AS duplicate_type, org_id || ':' || station_id AS duplicate_key, COUNT(*) AS row_count
  FROM engineer_assignments WHERE scope_type = 'STATION' AND station_id IS NOT NULL
 GROUP BY org_id, station_id HAVING COUNT(*) > 1;
SELECT 'category engineer routing' AS duplicate_type, org_id || ':' || category_id AS duplicate_key, COUNT(*) AS row_count
  FROM engineer_assignments WHERE scope_type = 'CATEGORY' AND category_id IS NOT NULL
 GROUP BY org_id, category_id HAVING COUNT(*) > 1;

WITH required(name) AS (
  VALUES ('ux_contractors_portal_user'),('ux_technicians_portal_user'),
         ('ux_engineer_assignments_station'),('ux_engineer_assignments_category')
)
SELECT required.name AS missing_unique_index FROM required
LEFT JOIN sqlite_schema ON sqlite_schema.type = 'index' AND sqlite_schema.name = required.name
WHERE sqlite_schema.name IS NULL;

SELECT key AS retired_permission_still_present FROM permissions
 WHERE key IN (${RETIRED_PERMISSIONS.map(q).join(',')}) ORDER BY key;

DROP TABLE IF EXISTS temp._expected_rbac;
CREATE TEMP TABLE _expected_rbac (role_code TEXT NOT NULL, permission_key TEXT NOT NULL, PRIMARY KEY (role_code, permission_key));
INSERT INTO _expected_rbac (role_code, permission_key) VALUES
${values(pairs)};

SELECT e.permission_key AS missing_permission
FROM (SELECT DISTINCT permission_key FROM _expected_rbac) e
LEFT JOIN permissions p ON p.key = e.permission_key
WHERE p.id IS NULL ORDER BY e.permission_key;

WITH standard(code) AS (VALUES ${standardCodes.map((code) => `(${q(code)})`).join(',')})
SELECT standard.code AS missing_standard_role FROM standard
LEFT JOIN roles r ON r.org_id IS NULL AND r.code = standard.code
WHERE r.id IS NULL ORDER BY standard.code;

SELECT r.org_id, r.code, r.name, e.permission_key AS missing_grant
FROM roles r JOIN _expected_rbac e ON e.role_code = r.code
JOIN permissions p ON p.key = e.permission_key
LEFT JOIN role_permissions rp ON rp.role_id = r.id AND rp.permission_id = p.id
WHERE rp.role_id IS NULL ORDER BY r.code, r.org_id, e.permission_key;

SELECT r.org_id, r.code, r.name, p.key AS unexpected_grant
FROM roles r JOIN role_permissions rp ON rp.role_id = r.id
JOIN permissions p ON p.id = rp.permission_id
LEFT JOIN _expected_rbac e ON e.role_code = r.code AND e.permission_key = p.key
WHERE r.code IN (${standardCodes.map(q).join(',')}) AND e.permission_key IS NULL
ORDER BY r.code, r.org_id, p.key;

SELECT r.org_id, r.code, r.name, COUNT(rp.permission_id) AS grant_count
FROM roles r LEFT JOIN role_permissions rp ON rp.role_id = r.id
WHERE r.code IN (${standardCodes.map(q).join(',')}) GROUP BY r.id, r.org_id, r.code, r.name
ORDER BY r.code, r.org_id;

SELECT r.org_id, r.code, r.name, COUNT(rp.permission_id) AS custom_grant_count
FROM roles r LEFT JOIN role_permissions rp ON rp.role_id = r.id
WHERE r.code NOT IN (${standardCodes.map(q).join(',')}) GROUP BY r.id, r.org_id, r.code, r.name
ORDER BY r.org_id, r.code;

DROP TABLE temp._expected_rbac;
`;
writeFileSync(new URL('./turso-web/13_check_comprehensive_rbac.sql', import.meta.url), checks);

const apply = `-- Run once, only after script 13 reports no duplicate portal/routing rows.
-- Drizzle Studio supplies the transaction; do not add BEGIN or COMMIT.
-- Standard-code organisation role copies are reset; custom role codes remain.
ALTER TABLE lpos ADD COLUMN submitted_at TEXT;
ALTER TABLE lpos ADD COLUMN submitted_by TEXT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE rfqs ADD COLUMN submitted_at TEXT;
ALTER TABLE rfqs ADD COLUMN submitted_by TEXT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE rfqs ADD COLUMN released_at TEXT;
ALTER TABLE rfqs ADD COLUMN released_by TEXT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE pm_schedules ADD COLUMN created_by TEXT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE pm_schedules ADD COLUMN activated_by TEXT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE pm_schedules ADD COLUMN activated_at TEXT;

UPDATE lpos SET submitted_at = COALESCE(submitted_at, created_at), submitted_by = COALESCE(submitted_by, created_by),
  approved_at = COALESCE(approved_at, created_at), approved_by = COALESCE(approved_by, created_by),
  issued_at = COALESCE(issued_at, created_at), issued_by = COALESCE(issued_by, created_by);
UPDATE rfqs SET submitted_at = COALESCE(submitted_at, created_at), submitted_by = COALESCE(submitted_by, created_by),
  released_at = COALESCE(released_at, created_at), released_by = COALESCE(released_by, created_by);
UPDATE pm_schedules AS schedule SET created_by = COALESCE(created_by,
  (SELECT actor_user_id FROM audit_logs WHERE org_id = schedule.org_id AND entity_type = 'pm_schedule'
   AND entity_id = schedule.id AND action = 'pm.schedule.create' ORDER BY created_at ASC LIMIT 1));
UPDATE pm_schedules SET activated_at = COALESCE(activated_at, created_at),
  activated_by = COALESCE(activated_by, created_by) WHERE status = 'ACTIVE';

CREATE UNIQUE INDEX IF NOT EXISTS ux_contractors_portal_user ON contractors(portal_user_id) WHERE portal_user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_technicians_portal_user ON technicians(portal_user_id) WHERE portal_user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_engineer_assignments_station ON engineer_assignments(org_id, station_id) WHERE scope_type = 'STATION';
CREATE UNIQUE INDEX IF NOT EXISTS ux_engineer_assignments_category ON engineer_assignments(org_id, category_id) WHERE scope_type = 'CATEGORY';

${retiredSql}

${permissionSql}

${rolesSql}

${grantSql}

INSERT OR IGNORE INTO schema_migrations (id, description, checksum)
VALUES ('006', ${q(comprehensiveRbac.description)}, ${q(comprehensiveRbac.checksum)});

SELECT id, description, checksum, applied_at FROM schema_migrations ORDER BY id;
`;
writeFileSync(new URL('./turso-web/14_apply_comprehensive_rbac.sql', import.meta.url), apply);

console.log(`Generated RBAC seed and Turso scripts for ${RBAC_PERMISSIONS.length} permissions.`);
